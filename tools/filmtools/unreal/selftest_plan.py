"""`film-ue selftest plan`: tomorrow's GPU-box run, read OFFLINE from the selftest modules (unreal/fmbridge/selftest/
<area>.py: their docstrings' "Takes ..." and "Needs: ...", REQUIRES, AREAS, TIMEOUT), in dependency order: the gates
first (platform: the bridge and editor; dx: the registry, errors, specs), then the areas in build order (assets,
layout, look, mh, anim, seq, cam, render, qa, audio), then the rest. `film-ue selftest` (all) runs in this order and
stops after a failed gate. --md prints the table for docs/unreal/MORNING-REPORT.md verbatim (BACKLOG B46)."""
from __future__ import annotations

import ast
import re
from pathlib import Path

from . import schema as _schema

SELFTESTS = _schema.ROOT / "unreal" / "fmbridge" / "selftest"
GATES = ("platform", "dx")
ORDER = ("platform", "dx", "assets", "layout", "look", "mh", "anim", "perf", "seq", "cam", "render", "qa", "audio")
DEPENDS = {  # what a selftest relies on having passed (beyond the gates); shown in the plan
    "mh": ["epic_login for part 2 (cloud rig, textures, build)"],
    "cam": ["render path (view.still) proven by qa or render"], "qa": ["gpu"], "render": ["gpu"],
}


def _seconds(text: str) -> float | None:
    """The first duration in "Takes ~2 min" / "Takes about 10 s" / "~1.5 min" form, in seconds."""
    m = re.search(r"[Tt]akes\s*(?:about|around|~|roughly)?\s*~?\s*([\d.]+)\s*(?:-\s*[\d.]+\s*)?"
                  r"(s|sec|secs|seconds?|min|mins|minutes?|h|hours?)\b", text)
    if not m:
        return None
    v, unit = float(m.group(1)), m.group(2)
    return v * (3600 if unit.startswith("h") else 60 if unit.startswith("m") else 1)


def _needs(text: str) -> str:
    m = re.search(r"Needs:\s*(.+?)(?:\.\s|\.$|\n\n|$)", " ".join(text.split()))
    return m.group(1).strip() if m else ""


def modules() -> list:
    out = []
    for p in sorted(SELFTESTS.glob("*.py")):
        if p.stem.startswith("_"):
            continue
        try:
            tree = ast.parse(p.read_text(errors="replace"), feature_version=(3, 11))
        except SyntaxError as e:
            out.append({"name": p.stem, "error": f"does not parse: {e.msg} (line {e.lineno})"})
            continue
        doc = ast.get_docstring(tree) or ""
        consts = {}
        for n in tree.body:
            if isinstance(n, ast.Assign):
                for t in n.targets:
                    if isinstance(t, ast.Name) and t.id in ("REQUIRES", "AREAS", "TIMEOUT", "NEEDS_LEVEL"):
                        try:
                            consts[t.id] = ast.literal_eval(n.value)
                        except ValueError:
                            pass
        est = _seconds(doc)
        out.append({"name": p.stem, "summary": " ".join(doc.split("\n\n")[0].split())[:160],
                    "areas": list(consts.get("AREAS", [p.stem])), "requires": list(consts.get("REQUIRES", [])),
                    "timeout_s": float(consts.get("TIMEOUT", 900)), "needs_level": consts.get("NEEDS_LEVEL", True),
                    "estimate_s": est, "needs": _needs(doc), "gate": p.stem in GATES,
                    "depends": DEPENDS.get(p.stem, [])})
    return out


def _rank(m: dict) -> tuple:
    keys = [m["name"]] + m.get("areas", [])
    pos = min((ORDER.index(k) for k in keys if k in ORDER), default=len(ORDER))
    return (pos, m["name"])


def plan() -> dict:
    mods = sorted(modules(), key=_rank)
    est = sum(m.get("estimate_s") or 0 for m in mods)
    unknown = [m["name"] for m in mods if m.get("estimate_s") is None and "error" not in m]
    worst = sum(m.get("timeout_s", 0) for m in mods)
    return {"order": [m["name"] for m in mods], "selftests": mods, "estimate_s": est, "unknown_estimates": unknown,
            "worst_case_s": worst, "gates": [m for m in GATES if any(x["name"] == m for x in mods)],
            "epic_login": [m["name"] for m in mods if _wants_epic(m)]}


def _wants_epic(m: dict) -> bool:
    if {"epic_login", "mh_cloud"} & set(m.get("requires", [])):
        return True
    text = (m.get("needs", "") + " " + " ".join(m.get("depends", []))).lower()
    text = re.sub(r"\bno (epic )?(sign-in|login|epic sign-in|epic login)", "", text)
    return bool(re.search(r"epic|sign-in", text))


def _dur(s) -> str:
    if s is None:
        return "?"
    return f"{s:.0f} s" if s < 90 else f"{s / 60:.1f} min"


def markdown(p: dict) -> str:
    lines = ["### Selftest run plan (GPU box)", "",
             "Generated by `film-ue selftest plan --md` from the selftest modules. Run all of it with `film-ue selftest`",
             f"(this order; it stops after a failed gate: {', '.join(p['gates'])}), or one area at a time with "
             "`film-ue selftest <name>`.", "",
             "Before: `film-ue --box NAME first-run --epic` (it runs doctor, installs the bridge and passes platform + dx; "
             "then `film-ue selftest --list` shows the capabilities: gpu, epic_login)" +
             (f"; `film-ue epic-login` first if epic_login is no (needed by: {', '.join(p['epic_login'])})."
              if p["epic_login"] else "."), "",
             "| # | selftest | covers | REQUIRES (else skipped) | needs | est. | timeout | gate |",
             "|---|---|---|---|---|---|---|---|"]
    for i, m in enumerate(p["selftests"], 1):
        if "error" in m:
            lines.append(f"| {i} | {m['name']} | BROKEN: {m['error']} | | | | | |")
            continue
        needs = (m["needs"] or "").replace("|", "/")
        needs = needs if len(needs) <= 110 else needs[:107] + "..."
        lines.append(f"| {i} | `{m['name']}` | {', '.join(m['areas'])} | {', '.join(m['requires']) or '-'} | "
                     f"{needs or '-'} | {_dur(m['estimate_s'])} | {_dur(m['timeout_s'])} | {'yes' if m['gate'] else ''} |")
    lines += ["", f"Estimated total: {_dur(p['estimate_s'])}" +
              (f" plus {', '.join(p['unknown_estimates'])} (no estimate in their docstrings)" if p["unknown_estimates"] else "")
              + f"; worst case (every TIMEOUT): {_dur(p['worst_case_s'])}.",
              "Afterwards: `selftest-reports/<time>/summary.md`; then the demo (examples/unreal/demo/README.md)."]
    return "\n".join(lines) + "\n"


def text(p: dict) -> str:
    out = []
    for i, m in enumerate(p["selftests"], 1):
        if "error" in m:
            out.append(f"{i:>2}. {m['name']:<10} BROKEN: {m['error']}")
            continue
        out.append(f"{i:>2}. {m['name']:<10} {_dur(m['estimate_s']):>8} (timeout {_dur(m['timeout_s'])})  "
                   f"needs {', '.join(m['requires']) or 'nothing'}{'  GATE' if m['gate'] else ''}  covers "
                   f"{', '.join(m['areas'])}")
    out.append(f"\nestimated {_dur(p['estimate_s'])}, worst case {_dur(p['worst_case_s'])}"
               + (f"; no estimate: {', '.join(p['unknown_estimates'])}" if p["unknown_estimates"] else ""))
    return "\n".join(out)
