"""Generate filmtools/unreal/sdk/_generated.py from the op schema: `film-ue dx gen` (or `python -m
filmtools.unreal.sdk.gen`). The file is committed; tests/test_unreal_dx.py fails when it is older than the ops."""
from __future__ import annotations

import json
import keyword
import textwrap
from pathlib import Path

from .. import schema as _schema

OUT = Path(__file__).with_name("_generated.py")
PY = {"int": "int", "float": "float", "bool": "bool", "str": "str", "list": "list", "dict": "dict", "any": "Any"}


def ident(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) or name in ("self",) else name


def class_name(area: str) -> str:
    return "".join(p.capitalize() for p in area.split("_")) + "Ops"


def _ann(p: dict) -> str:
    t = PY.get(p["value"], "Any")
    return f"{t} | None" if p["nullable"] and t != "Any" else t


def _doc(o: dict) -> str:
    lines = [(o.get("doc") or o.get("summary") or o["name"]).strip(), ""]
    if o["params"]:
        lines.append("Args:")
        for p in o["params"]:
            d = "required" if p["required"] else f"default {json.dumps(p['default'])}"
            lines.append(f"    {p['name']} ({p.get('type') or p['value']}, {d}){': ' + p['help'] if p.get('help') else ''}")
    flags = [k for k in ("mutates", "idempotent") if o.get(k) is not None]
    lines.append("")
    lines.append(f"Op: {o['name']}" + (f"  ({o['file']}:{o['line']})" if o.get("file") else "") +
                 ("  multi-tick" if o.get("multi_tick") else "") +
                 "".join(f"  {k}={o[k]}" for k in flags) + (f"  tags={o['tags']}" if o.get("tags") else ""))
    if o.get("returns"):
        lines.append(f"Returns: {o['returns']}")
    return "\n".join(lines).replace('"""', "'''").replace("\\", "\\\\")


def _method(o: dict) -> str:
    req = [p for p in o["params"] if p["required"]]
    opt = [p for p in o["params"] if not p["required"]]
    sig = ["self", "*"] if o["params"] else ["self"]
    sig += [f"{ident(p['name'])}: {_ann(p)}" for p in req]
    sig += [f"{ident(p['name'])}: {_ann(p)} = UNSET" for p in opt]
    if not o["params"]:
        sig.append("*")
    sig += ["_wait: bool = True", "_timeout: float = 900"]
    ret = o.get("returns") or ""
    ret = ret if ret in ("dict", "list", "str", "int", "float", "bool") else "Any"
    args = ", ".join(f"{p['name']!r}: {ident(p['name'])}" for p in o["params"])
    doc = textwrap.indent(_doc(o), "    ").lstrip()
    body = (f"def {ident(o['verb'])}({', '.join(sig)}) -> {ret}:\n"
            f'    """{doc}\n    """\n'
            f"    return self._call({o['name']!r}, {{{args}}}, _wait, _timeout)\n")
    return textwrap.indent(body, "    ")


def generate(index: dict | None = None) -> str:
    ix = index or _schema.index(_schema.load())
    out = [f'"""GENERATED by filmtools.unreal.sdk.gen from the op schema (fingerprint {ix["fingerprint"]}): do not edit.\n'
           f'Regenerate with `film-ue dx gen`."""',
           "from __future__ import annotations", "", "from typing import Any", "", "from . import UNSET, _Area", "",
           f"FINGERPRINT = {ix['fingerprint']!r}", ""]
    areas = {}
    for area, a in ix["areas"].items():
        cls = class_name(area)
        areas[area] = cls
        doc = (a.get("doc") or f"The {area} ops.").replace('"""', "'''")
        out += ["", f"class {cls}(_Area):", f'    """{doc}"""', f"    _area = {area!r}", ""]
        for name in a["ops"]:
            out.append(_method(ix["ops"][name]))
    out += ["", "AREAS = {" + ", ".join(f"{a!r}: {c}" for a, c in areas.items()) + "}", ""]
    return "\n".join(out)


def write(path: Path = OUT) -> Path:
    path.write_text(generate())
    return path


if __name__ == "__main__":
    print(write())
