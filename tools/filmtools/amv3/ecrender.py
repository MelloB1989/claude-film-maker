"""Timeless v3: run EffectCraft renders on the render VM through the render queue (chunked), check and encode the frames.

Shared by ecfinish.py and standin.py. Same recipe as v2 (`filmtools.amv2.render`, skill ref 16 gotcha 8): many short
`effectcraft-cli render` processes (48 frames each: the CLI's RSS grows with every frame it renders), `procs` at a time
with RAYON_NUM_THREADS=`threads`, one retry per chunk. The VM gets the worktree synced (without .git and out/) and copies
the job's `out` dir back. Python 3.10 on the VM: no 3.11+ syntax in anything the job runs.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
QUEUE = Path("/home/nikhil/code/.renderq")
FILM_BIN = Path("/home/nikhil/code/film-making/bin")
FFMPEG = str(FILM_BIN / "ffmpeg") if (FILM_BIN / "ffmpeg").exists() else "ffmpeg"
LOCAL_CLI = FILM_BIN / "artcraft/effectcraft-0.10.0-linux-x86_64/bin/effectcraft-cli"
FPS = 30


def local_cli():
    c = os.environ.get("EFFECTCRAFT_CLI")
    if c:
        return c
    return str(LOCAL_CLI) if LOCAL_CLI.exists() else "effectcraft-cli"


def rel(p):
    """Path relative to the worktree root (what the VM job sees as its cwd)."""
    return str(Path(p).resolve().relative_to(ROOT))


def chunks(a, b, size=48):
    """[a, b) cut into near-equal consecutive chunks of at most `size` frames."""
    n = max(1, -(-(b - a) // size))
    q, r = divmod(b - a, n)
    out, s = [], a
    for i in range(n):
        e = s + q + (1 if i < r else 0)
        out.append((s, e))
        s = e
    return out


def write_runner(name, proj_rel, comp, fdir_rel, ch, procs=2, threads=8, res="full", quality="best"):
    """`build/amv3/<name>_run.sh`: an xargs queue of chunk processes. Prints `CHUNK a b rc= try= secs= rss_mb=` per chunk.
    `--start (A-0.25)/fps --end (B-0.75)/fps` renders exactly frames A..B-1 (EFFECTCRAFT-NOTES v2-core)."""
    bdir = ROOT / "build/amv3"
    bdir.mkdir(parents=True, exist_ok=True)
    (bdir / f"{name}_chunks.txt").write_text("".join(f"{s} {e} {i}\n" for i, (s, e) in enumerate(ch)))
    run = bdir / f"{name}_run.sh"
    run.write_text(f"""#!/bin/bash
# generated by filmtools.amv3.ecrender: chunk queue for {proj_rel}
cd "$(dirname "$0")/../.."
FD={fdir_rel}; mkdir -p $FD
export RAYON_NUM_THREADS={threads}
run() {{
  s=$1; e=$2; i=$3
  for try in 1 2; do
    t0=$(date +%s.%N); peak=0
    effectcraft-cli --project {proj_rel} render --comp {comp} --format png \\
      --start $(awk "BEGIN{{printf \\"%.6f\\", ($s - 0.25) / {FPS}}}") --end $(awk "BEGIN{{printf \\"%.6f\\", ($e - 0.75) / {FPS}}}") \\
      --resolution {res} --quality {quality} --out $FD/f > /dev/null 2> $FD/err_${{i}}_$try.txt &
    pid=$!
    while kill -0 $pid 2>/dev/null; do
      v=$(awk '/VmHWM/ {{print $2}}' /proc/$pid/status 2>/dev/null); [ -n "$v" ] && [ "$v" -gt "$peak" ] && peak=$v
      sleep 1
    done
    wait $pid
    rc=$?
    [ $rc -eq 0 ] && break
    echo "RETRY chunk $s $e rc=$rc"
  done
  echo "CHUNK $s $e rc=$rc try=$try secs=$(echo "$(date +%s.%N) - $t0" | bc) rss_mb=$((peak / 1024))"
}}
export -f run; export FD
xargs -a build/amv3/{name}_chunks.txt -P {procs} -L 1 bash -c 'run $0 $1 $2'
""")
    run.chmod(0o755)
    return rel(run)


def submit(name, cmd, out_rel, threads=16):
    """Drop a queue job (replacing an old one of the same name); returns the job name."""
    for ext in ("done", "log", "started"):
        (QUEUE / f"{name}.{ext}").unlink(missing_ok=True)
    tree = str(ROOT.relative_to("/home/nikhil/code"))
    (QUEUE / f"{name}.json").write_text(json.dumps(dict(tree=tree, cmd=cmd, out=out_rel, threads=threads)))
    return name


def wait(name, timeout=3 * 3600):
    t0 = time.time()
    done = QUEUE / f"{name}.done"
    while not done.exists():
        if time.time() - t0 > timeout:
            raise SystemExit(f"render job {name} timed out")
        time.sleep(3)
    log = (QUEUE / f"{name}.log").read_text() if (QUEUE / f"{name}.log").exists() else ""
    return int(done.read_text().strip() or 0), log, time.time() - t0


def chunk_stats(log):
    return [dict(zip(("a", "b", "rc", "try", "secs", "rss_mb"), m))
            for m in re.findall(r"CHUNK (\d+) (\d+) rc=(\d+) try=(\d+) secs=([\d.]+) rss_mb=(\d+)", log)]


def missing(fdir, a, b):
    return [f for f in range(a, b) if not (Path(fdir) / f"f_{f:05d}.png").exists()]


def encode(fdir, a, b, mp4, audio=None, crf=16):
    """h264 CRF `crf` yuv420p +faststart, audio from `audio` starting at frame a (else silent)."""
    cmd = [FFMPEG, "-y", "-v", "error", "-framerate", str(FPS), "-start_number", str(a), "-i", str(Path(fdir) / "f_%05d.png")]
    if audio:
        cmd += ["-ss", f"{a / FPS}", "-i", str(audio), "-map", "0:v", "-map", "1:a", "-c:a", "aac", "-b:a", "256k"]
    cmd += ["-frames:v", str(b - a), "-c:v", "libx264", "-crf", str(crf), "-preset", "medium", "-pix_fmt", "yuv420p",
            "-vf", "scale=1920:1080:flags=lanczos", "-t", f"{(b - a) / FPS}", "-movflags", "+faststart", str(mp4)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("encode failed: " + r.stderr[-800:])
