"""Timeless v2: render the EffectCraft project on the 16-core render VM and encode the mp4.

    python -m filmtools.amv2.render [--draft] [--frames A-B] [--procs 4] [--threads 4] [--src clips|src240]
                                    [--no-build] [--no-encode] [--name NAME]
    python -m filmtools.amv2.render bench [--frames A-B] [--splits 1x16,2x8,4x4,8x2]

1. (re)builds the project with ecbuild (`--draft`: half resolution, 4 motion-blur samples; else full, 16) into
   `build/amv2/<name>.ecproj` (inside the worktree: the render queue syncs the tree but not `out/`);
2. splits the frames into chunks, drops ONE render-queue job whose command runs `procs` `effectcraft-cli render
   --format png` processes in parallel on the VM (each with RAYON_NUM_THREADS=threads: the CLI's thread knob), and waits;
3. checks every PNG (all frames present, no black frames except where intended: signalstats YAVG);
4. encodes h264 (CRF 16, yuv420p, +faststart) with $AMV2_DATA/mix.wav, else out/timeless/amv2/mix.wav, else the song's 0-30 s;
5. writes a 6x5 contact sheet and `timings.json` (seconds per frame, per chunk).
Output: out/timeless/amv2/{frames[_draft]/f_NNNNN.png, Timeless_v2[_draft].mp4, contact[_draft].png}.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
import time
from pathlib import Path

from . import ecbuild

ROOT = ecbuild.ROOT
OUT = ecbuild.OUT_DIR
QUEUE = Path("/home/nikhil/code/.renderq")
VM_CLI = "effectcraft-cli"
FFMPEG = str(ecbuild.FILM_BIN / "ffmpeg")
SONG = "/home/nikhil/code/film-making/handover/amv_handover/audio/timeless_full.wav"
DUR = 900
FPS = 30
BLACK_OK = {0, 1}          # frames that are black on purpose (S01 fades up from black)


def parse_frames(s, dur=DUR):
    if not s:
        return 0, dur
    a, b = s.split("-")
    return int(a), min(int(b) + 1, dur)      # inclusive on the command line


def chunks(a, b, n):
    """Split [a, b) into n near-equal consecutive chunks (no empty ones)."""
    n = max(1, min(n, b - a))
    q, r = divmod(b - a, n)
    out, s = [], a
    for i in range(n):
        e = s + q + (1 if i < r else 0)
        out.append((s, e))
        s = e
    return out


def tree_rel(p):
    return str(Path(p).resolve().relative_to("/home/nikhil/code"))


def run_job(name, cmd, out_rel, threads, timeout=3 * 3600):
    job = QUEUE / f"{name}.json"
    for ext in ("done", "log", "started"):
        (QUEUE / f"{name}.{ext}").unlink(missing_ok=True)
    job.write_text(json.dumps(dict(tree=tree_rel(ROOT), cmd=cmd, out=out_rel, threads=threads)))
    t0 = time.time()
    done = QUEUE / f"{name}.done"
    while not done.exists():
        if time.time() - t0 > timeout:
            raise SystemExit(f"render job {name} timed out")
        time.sleep(3)
    log = (QUEUE / f"{name}.log").read_text() if (QUEUE / f"{name}.log").exists() else ""
    rc = int(done.read_text().strip() or 0)
    return rc, log, time.time() - t0


PREFS = {"memory": {"layerCacheMb": 768, "mediaCacheMb": 1536, "previewCacheMb": 0, "reduceCacheWhenLow": True},
         "disk": {"diskCacheEnabled": False}}      # EffectCraft prefs.json cache budgets (see docs/EFFECTCRAFT-NOTES.md)


def write_runner(name, proj_rel, fdir_rel, ch, workers, threads, res, quality, cache=True):
    """A bash runner (in the synced tree, `build/amv2/<name>_run.sh`): a queue of short chunks, `workers` at a time
    (xargs -P), each chunk its own effectcraft-cli process that exits when done (the CLI's RSS grows with the frames it
    renders, so no process lives long). A chunk that dies (OOM kill = rc 137) is retried once. Per chunk it prints
    `CHUNK a b rc=.. try=.. secs=.. rss_mb=..` (peak RSS = VmHWM polled from /proc: the VM has no /usr/bin/time)."""
    cfg = f"build/amv2/cfg_{name}"
    run = ROOT / "build/amv2" / f"{name}_run.sh"
    cfgdir = ROOT / cfg
    cfgdir.mkdir(parents=True, exist_ok=True)
    (cfgdir / "prefs.json").write_text(json.dumps(PREFS if cache else {}))
    (ROOT / "build/amv2" / f"{name}_chunks.txt").write_text("".join(f"{s} {e} {i}\n" for i, (s, e) in enumerate(ch)))
    script = f"""#!/bin/bash
# generated by filmtools.amv2.render: chunk queue for {proj_rel}
cd "$(dirname "$0")/../.."
FD={fdir_rel}; mkdir -p $FD
export EFFECTCRAFT_CONFIG_DIR=$PWD/{cfg} RAYON_NUM_THREADS={threads}
run() {{
  s=$1; e=$2; i=$3
  for try in 1 2; do
    t0=$(date +%s.%N); peak=0
    {VM_CLI} --project {proj_rel} render --comp MAIN --format png \\
      --start $(awk "BEGIN{{printf \\"%.6f\\", ($s - 0.25) / {FPS}}}") --end $(awk "BEGIN{{printf \\"%.6f\\", ($e - 0.75) / {FPS}}}") \\
      --resolution {res} --quality {quality} --out $FD/f > /dev/null 2> $FD/err_${{i}}_$try.txt &
    pid=$!
    while kill -0 $pid 2>/dev/null; do                       # peak RSS (VmHWM) of the process, polled
      v=$(awk '/VmHWM/ {{print $2}}' /proc/$pid/status 2>/dev/null); [ -n "$v" ] && [ "$v" -gt "$peak" ] && peak=$v
      sleep 1
    done
    wait $pid
    rc=$?
    [ $rc -eq 0 ] && break
    echo "RETRY chunk $s $e rc=$rc"
  done
  echo "CHUNK $s $e rc=$rc try=$try secs=$(echo "$(date +%s.%N) - $t0" | bc) rss_mb=$((peak / 1024))"
}}
export -f run; export FD
xargs -a build/amv2/{name}_chunks.txt -P {workers} -L 1 bash -c 'run $0 $1 $2'
"""
    run.write_text(script)
    run.chmod(0o755)
    return str(run.relative_to(ROOT))


def vm_cmd(project_rel, frames_dir_rel, runner_rel, build_args=None):
    """(see below) Built projects are also kept in $AMV2_DATA/builds/ on the VM: the queue rsyncs the tree with --delete
    before every job, so build/amv2/<name>.ecproj from an earlier job is gone; --no-build restores it from there."""
    return _vm_cmd(project_rel, frames_dir_rel, runner_rel, build_args)


def _vm_cmd(project_rel, frames_dir_rel, runner_rel, build_args=None):
    """The shell command of the queue job: (optionally) build the project on the VM, then run the chunk queue.
    `build_args` (list): $AMV2_DATA (the 240 fps sources and mattes) only exists there, and ecbuild probes it."""
    keep = f"$AMV2_DATA/builds/{os.path.basename(project_rel)}"
    wb = f"AMV2_WBLUR={os.environ.get('AMV2_WBLUR', '1')} "
    pre = ""
    if build_args is None:
        pre = (f"mkdir -p build/amv2 && [ -f {project_rel} ] && keep_ok=1 || [ -f {keep} ] || {{ echo 'no kept build {keep}: run once without --no-build'; exit 3; }}; "
               f"[ -f {project_rel} ] || cp {keep} {project_rel}; ")
    if build_args is not None:
        pre = (f"mkdir -p {frames_dir_rel} && (cd tools && {wb}python -m filmtools.amv2.ecbuild --out ../{project_rel} "
               f"{' '.join(build_args)}) > {frames_dir_rel}/build.log 2>&1; brc=$?; echo BUILD rc=$brc; "
               f"tail -n 6 {frames_dir_rel}/build.log; [ $brc -eq 0 ] || exit $brc; cp {project_rel} {frames_dir_rel}/; "
               f"mkdir -p $AMV2_DATA/builds && cp {project_rel} {keep}; ")
    return pre + f"bash {runner_rel}"


def split_chunks(a, b, size):
    """[a, b) cut into chunks of at most `size` frames (near-equal)."""
    n = -(-(b - a) // size)
    return chunks(a, b, n)


def check_frames(fdir, a, b):
    """Every frame present; black frames listed (YAVG < 17: black is 16 in limited-range YUV) so the caller can compare with the intended ones."""
    miss = [f for f in range(a, b) if not (fdir / f"f_{f:05d}.png").exists()]
    black = []
    if not miss:
        r = subprocess.run([FFMPEG, "-v", "error", "-start_number", str(a), "-i", str(fdir / "f_%05d.png"), "-frames:v",
                            str(b - a), "-vf", "signalstats,metadata=print:key=lavfi.signalstats.YAVG:file=-", "-f", "null", "-"],
                           capture_output=True, text=True)
        ys = [float(x) for x in re.findall(r"YAVG=([\d.]+)", r.stdout)]
        black = [a + i for i, y in enumerate(ys) if y < 17.0]
    return miss, black


def encode(fdir, a, b, mp4, mix=None, fps=FPS):
    if not mix:      # the final mix: $AMV2_DATA/mix.wav, then out/timeless/amv2/mix.wav, then the song's 0-30 s
        mix = next((m for m in (ecbuild.data_dir() / "mix.wav", OUT / "mix.wav") if m.exists()), None)
    cmd = [FFMPEG, "-y", "-v", "error", "-framerate", str(fps), "-start_number", str(a), "-i", str(fdir / "f_%05d.png")]
    if mix:
        cmd += ["-ss", f"{a / fps}", "-i", str(mix)]
    else:
        cmd += ["-ss", f"{a / fps}", "-t", f"{(b - a) / fps}", "-i", SONG]
    cmd += ["-map", "0:v", "-map", "1:a", "-frames:v", str(b - a), "-c:v", "libx264", "-crf", "16", "-preset", "medium", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-b:a", "256k", "-t", f"{(b - a) / fps}", "-movflags", "+faststart", str(mp4)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("encode failed: " + r.stderr[-800:])
    return mix


def contact_sheet(fdir, a, b, out, cols=6, rows=5, w=320):
    n = cols * rows
    idx = [a + round(i * (b - a - 1) / (n - 1)) for i in range(n)]
    ins = []
    for f in idx:
        ins += ["-i", str(fdir / f"f_{f:05d}.png")]
    sc = "".join(f"[{i}:v]scale={w}:-2[s{i}];" for i in range(n))
    rowsx = "".join(f"{''.join(f'[s{r * cols + c}]' for c in range(cols))}hstack={cols}[r{r}];" for r in range(rows))
    fc = sc + rowsx + "".join(f"[r{r}]" for r in range(rows)) + f"vstack={rows}"
    r = subprocess.run([FFMPEG, "-y", "-v", "error"] + ins + ["-filter_complex", fc, "-frames:v", "1", str(out)],
                       capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("contact sheet failed: " + r.stderr[-500:])
    return idx


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", nargs="?", default="render", choices=("render", "bench"))
    ap.add_argument("--draft", action="store_true")
    ap.add_argument("--frames", default=None, help="A-B inclusive")
    ap.add_argument("--procs", type=int, default=2, help="parallel effectcraft-cli workers on the VM")
    ap.add_argument("--threads", type=int, default=8, help="RAYON_NUM_THREADS per process")
    ap.add_argument("--chunk", type=int, default=48, help="frames per effectcraft-cli process (it exits after a chunk)")
    ap.add_argument("--cache-prefs", action="store_true", help="write PREFS (cache budgets) into EFFECTCRAFT_CONFIG_DIR: measured no effect on RSS (6.2 vs 6.1 GB / 96 f)")
    ap.add_argument("--src", choices=("clips", "src240"), default="src240")
    ap.add_argument("--local-build", action="store_true", help="build here (needs $AMV2_DATA locally, or --src clips)")
    ap.add_argument("--samples", type=int, default=None)
    ap.add_argument("--name", default=None)
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--no-encode", action="store_true")
    ap.add_argument("--splits", default="1x16,2x8,4x4,8x2")
    a = ap.parse_args(argv)
    tag = "_draft" if a.draft else ""
    name = a.name or f"timeless_v2{tag}"
    proj = ROOT / "build/amv2" / f"{name}.ecproj"
    proj.parent.mkdir(parents=True, exist_ok=True)
    bargs = ["--src", a.src] + (["--draft"] if a.draft else []) + (["--samples", str(a.samples)] if a.samples else [])
    vm_build = not a.no_build and not a.local_build and a.src == "src240"
    if not a.no_build and not vm_build:
        rc = ecbuild.main(["--out", str(proj), "--src", a.src] + (["--draft"] if a.draft else [])
                          + (["--samples", str(a.samples)] if a.samples else []))
        if rc:
            raise SystemExit("ecbuild reported warnings/errors; fix them first")
    res = "half" if a.draft else "full"
    f0, f1 = parse_frames(a.frames)
    fdir = OUT / f"frames{tag}" if not a.name else OUT / f"frames_{a.name}"
    proj_rel = str(proj.relative_to(ROOT))
    fdir_rel = str(fdir.relative_to(ROOT))
    if a.cmd == "bench":
        res_rows = []
        for sp in a.splits.split(","):
            p, t = (int(x) for x in sp.split("x"))
            d = fdir_rel + f"/bench_{p}x{t}"
            ch = split_chunks(f0, f1, a.chunk)
            runner = write_runner(f"{name}-bench-{p}x{t}", proj_rel, d, ch, p, t, res, "best", a.cache_prefs)
            rc, log, secs = run_job(f"{name}-bench-{p}x{t}", vm_cmd(proj_rel, d, runner, bargs if vm_build else None), d, t)
            n = f1 - f0
            res_rows.append(dict(split=sp, frames=n, wall=round(secs, 1), per_frame=round(secs / n, 2), rc=rc))
            print(res_rows[-1], flush=True)
        (OUT / f"bench{tag}.json").write_text(json.dumps(res_rows, indent=1))
        return 0
    ch = split_chunks(f0, f1, a.chunk)
    runner = write_runner(name, proj_rel, fdir_rel, ch, a.procs, a.threads, res, "best", a.cache_prefs)
    t0 = time.time()
    rc, log, secs = run_job(f"{name}-render", vm_cmd(proj_rel, fdir_rel, runner, bargs if vm_build else None),
                          fdir_rel, a.procs * a.threads)
    print(log[-1500:])
    if vm_build and (fdir / f"{name}.ecproj").exists():
        import shutil
        shutil.copy(fdir / f"{name}.ecproj", OUT / ("timeless_v2_draft.ecproj" if a.draft else "timeless_v2.ecproj"))
    chunk_t = [dict(zip(("a", "b", "rc", "try", "secs", "rss_mb"), m))
               for m in re.findall(r"CHUNK (\d+) (\d+) rc=(\d+) try=(\d+) secs=([\d.]+) rss_mb=(\d+)", log)]
    miss, black = check_frames(fdir, f0, f1)
    unexpected = [f for f in black if f not in BLACK_OK]
    timings = dict(frames=[f0, f1], res=res, procs=a.procs, threads=a.threads, wall=round(secs, 1),
                   sec_per_frame=round(secs / (f1 - f0), 3), chunks=chunk_t, missing=miss, black=black)
    (OUT / f"timings{tag}.json").write_text(json.dumps(timings, indent=1))
    print(json.dumps({k: v for k, v in timings.items() if k != "chunks"}))
    if miss:
        raise SystemExit(f"{len(miss)} frames missing, first {miss[:10]}: see {fdir}/err*.txt")
    if unexpected:
        print(f"WARNING black frames not in the intended set: {unexpected}")
    if not a.no_encode:
        mp4 = OUT / f"Timeless_v2{tag}.mp4"
        mix = encode(fdir, f0, f1, mp4)
        print(f"encoded {mp4} (audio: {mix or 'song 0-30s'})")
        if f1 - f0 >= 30:
            idx = contact_sheet(fdir, f0, f1, OUT / f"contact{tag}.png")
            print(f"contact sheet {OUT / f'contact{tag}.png'} frames {idx}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
