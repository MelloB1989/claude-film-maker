"""The prosody timing for the presenter's gestures (round 7, agent-10): agent-11's acting sheet x her voice ->
acting/timing_<who>.json, which agent-01's gesturekit.plan_from_sheet(timing=...) reads (perform.py body --perform).

Every gesture is generated by code from this script's own voice (the operator, 07 Nov: no motion libraries, nothing
canned). The orchestrator's rules, 07 Nov:
- the stroke apex lands 80-200 ms BEFORE the stressed syllable's peak (prosody.py's loudest nucleus): the lead is
  shorter the more energy her voice has there (snappier), with a seeded jitter;
- the amplitude and the speed follow her local vocal energy: amp = the sheet's amp x (0.8 + 0.4 energy); the
  preparation takes 0.42 - 0.18 energy s, the retraction 0.45 - 0.2 energy s;
- beats on secondary stresses: strong syllables of content words between the sheet's gestures, where the hands would
  otherwise be still for more than ~1.2 s while she speaks; small, the right hand (the mic is on her left);
- rest in pauses over 0.6 s (gap_merge 0.6 for gesturekit's speak weight; no hold or retraction runs into one),
  except where the next stroke's preparation starts < 0.4 s after the pause: those are `bridge` pauses, the hands
  hold the high relaxed rest (the orchestrator, 08 Nov: a drop and rise at a cut reads twitchy);
- never the same type twice in a row among the added beats (the sheet's own deliberate pairs, e.g. the counting and
  N04's two naming beats, are the sheet's and are reported, not changed);
- the sheet's held strokes stay held (their hold_s) and still: no added beat lands inside any gesture's window.

    python gesture/prosody.py netflix && python gesture/plan.py netflix   -> acting/timing_her.json
"""
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXPL = HERE.parent
FILM_WHO = {"netflix": "her", "whatsapp": "him"}

LEAD = (0.08, 0.20)  # s before the stressed syllable's peak
PREP = (0.18, 0.30)  # s of preparation at full / no vocal energy (agent-09's gate counts a beat at > 40 cm/s)
AMP_MIN = 0.4  # the smallest stroke that still reads as a gesture (and passes 40 cm/s) on her rig
BRIDGE_PREP = 0.4  # s: a pause followed this soon by a stroke's preparation does not rest (bridge)
CHAIN = 0.6  # s: a gesture followed this soon by the next holds still until the next one's preparation
GAP_MERGE = 0.6  # s: pauses longer than this rest
STILL_MAX = 1.2  # s of still hands while speaking that calls for a beat on a secondary stress
BEAT_MIN_STRESS = 0.35
ADD_TYPES = (("beat", "beat"), ("open", "open_palm"), ("beat", "flick"), ("size", "pinch"))  # (body01 kind, detail)
STOP = {"a", "an", "the", "and", "but", "of", "to", "in", "on", "at", "it", "is", "its", "it's", "that", "that's",
        "for", "from", "so", "has", "have", "your", "you", "what", "will", "than", "then", "them", "their", "all",
        "be", "by", "with", "doesn't", "come", "into"}


def bare(w: str) -> str:
    return w.lower().strip(".,?!:;\"'")


def load(film: str):
    who = FILM_WHO[film]
    sheet = json.loads((EXPL / "acting" / f"{who}.json").read_text())
    cues = json.loads((EXPL / "audio" / film / "cues.json").read_text())
    pros = json.loads((HERE / "out" / f"prosody_{film}.json").read_text())
    return who, sheet, cues, pros


def speech_spans(cues, gap=GAP_MERGE) -> list:
    spans = []
    for ln in cues["lines"]:
        for w in ln["words"]:
            if spans and w["start"] - spans[-1][1] <= gap:
                spans[-1][1] = max(spans[-1][1], w["end"])
            else:
                spans.append([w["start"], w["end"]])
    return [tuple(s) for s in spans]


def span_of(t, spans):
    for a, b in spans:
        if a - 0.35 <= t <= b + 0.05:
            return (a, b)
    return None


def timed(e: dict, w: dict, rng, spans) -> dict:
    """prep/stroke/hold/retract/amp/energy for one gesture on word w (prosody)."""
    en = w["energy"]
    lead = LEAD[1] - (LEAD[1] - LEAD[0]) * en + rng.uniform(-0.015, 0.015)
    lead = min(LEAD[1], max(LEAD[0], lead))
    stroke = w["peak_t"] - lead
    prep = stroke - (PREP[1] - (PREP[1] - PREP[0]) * en) * rng.uniform(0.92, 1.08)
    if e.get("held"):
        hold = e.get("hold_s", 0.6)
    else:
        hold = (0.08 + 0.15 * (1 - en)) * rng.uniform(0.85, 1.15)
    retract = (0.45 - 0.2 * en) * rng.uniform(0.9, 1.1)
    sp = span_of(stroke, spans)
    if sp:  # no hold / retraction into a pause: it rests in the pause
        end = sp[1] + 0.25
        if stroke + hold + retract > end:
            if not e.get("held"):
                hold = max(0.06, min(hold, end - stroke - 0.25))
            retract = max(0.2, end - stroke - hold)
    amp = e.get("amp", 0.5) * (0.8 + 0.4 * en)
    return {"prep_t": round(prep, 3), "stroke_t": round(stroke, 3), "hold_s": round(hold, 3),
            "retract_s": round(retract, 3), "amp": round(min(1.0, max(AMP_MIN, amp)), 3), "energy": round(en, 3),
            "lead_s": round(lead, 3), "peak_t": w["peak_t"]}


def bridges(ev, spans) -> list:
    """Pauses (> GAP_MERGE) the hands do NOT rest in (the orchestrator, 08 Nov): where the next stroke's preparation
    starts < BRIDGE_PREP s after the pause ends, a drop to the desk and straight back up reads twitchy (and every long
    pause in her take holds a cut); the hands hold gesturekit's high relaxed rest instead. The other pauses rest."""
    out = []
    for (a0, a1), (b0, b1) in zip(spans, spans[1:]):
        nxt = min((e["prep_t"] for e in ev if e["prep_t"] >= a1 - 0.05), default=None)
        if nxt is not None and nxt - b0 < BRIDGE_PREP:
            out.append([round(a1, 3), round(b0, 3)])
    return out


def plan(film: str, seed: int = 72) -> dict:
    first = _plan(film, seed)
    br = bridges(first["gestures"], first["speech"])
    if not br:
        return first
    res = _plan(film, seed, br)  # again with the bridged pauses as speech (no rest, no retraction into them)
    res["bridge"] = br
    return res


def _plan(film: str, seed: int = 72, bridge: list | None = None) -> dict:
    who, sheet, cues, pros = load(film)
    rng = random.Random(seed)
    for gi, w in enumerate(pros["words"]):  # the sheet's word_i counts words over the whole film
        w["gi"] = gi
    words = {(w["line"], w["gi"]): w for w in pros["words"]}
    spans = speech_spans(cues)
    for b0, b1 in bridge or []:  # a bridged pause joins its two speech spans
        for i in range(len(spans) - 1):
            if abs(spans[i][1] - b0) < 1e-3 and abs(spans[i + 1][0] - b1) < 1e-3:
                spans[i:i + 2] = [(spans[i][0], spans[i + 1][1])]
                break
    fps = cues["fps"]
    out = []
    for ln in sheet["lines"]:
        for g in (ln.get("body01") or {}).get("gestures", []):
            w = words.get((ln["id"], g.get("word_i")))
            if not w:
                continue
            x = timed(g, w, rng, spans)
            out.append({"line": ln["id"], "word_i": g["word_i"], "word": g["word"], "src": "sheet",
                        "type": g.get("type"), "detail": g.get("detail"), "hand": g.get("hand"),
                        "held": bool(g.get("held")), **x})
    out.sort(key=lambda e: e["stroke_t"])
    out = add_beats(out, pros, sheet, spans, rng)
    chain(out)
    heights(out, film)
    for e in out:
        e["apex_f"] = int(round(e["stroke_t"] * fps))
    return {"_doc": "agent-10's prosody timing for gesturekit.plan_from_sheet(timing=...): per gesture (line, word_i) "
                    "prep_t / stroke_t (the apex, s on the VO clock; apex_f = the 24 fps frame) / hold_s / retract_s "
                    "/ amp / energy override the sheet's; entries with add: true are beats on secondary stresses "
                    "(type = body01 kind, detail, hand, size). gap_merge: pauses longer than this rest, except the "
                    "bridge pauses [[t0, t1]] (the hands hold the high relaxed rest). Written by "
                    "gesture/plan.py from gesture/prosody.py (vo.wav).",
            "film": film, "who": who, "fps": fps, "gap_merge": GAP_MERGE, "seed": seed,
            "gestures": out, "speech": spans, "stats": stats(out, spans)}


# agent-11's scale for small strokes (sheet d2d3e565): sternum in MCU / MCU_L / off camera, collarbone in CU,
# lower_chest in WIDE
APEX_HEIGHT = {"CAM_CU": "collarbone", "CAM_WIDE": "lower_chest"}


def heights(ev, film):
    """Each added beat's apex_height from the camera on screen at its apex (edl/<film>.json; agent-11's sheet gives
    the sheet's own): sternum height or higher, never at the desk (the orchestrator on side A: hands under the MCU frame)."""
    edl = json.loads((EXPL / "edl" / f"{film}.json").read_text())
    for e in ev:
        if e["src"] != "prosody":
            continue
        f = e["stroke_t"] * edl["fps"]
        cam = next((s.get("camera") for s in edl["shots"] if s["f0"] <= f < s["f1"] and s["kind"] in ("pres", "panel")),
                   None)
        e["camera"] = cam
        e["apex_height"] = APEX_HEIGHT.get(cam, "sternum")


def chain(ev):
    """Every stroke starts from stillness (a real post-stroke hold; and agent-09's gate only counts a beat that rises
    from under 10 cm/s): a gesture followed within CHAIN s holds still until the next one's preparation starts, then
    hands over to it over that preparation; one followed later retracts and settles >= 0.12 s before the next
    preparation. A held stroke that the next gesture's preparation interrupts keeps >= 0.25 s (the sheet sometimes
    places one inside another's hold: N04 'own' 0.5 s after the held 'builds')."""
    for a, b in zip(ev, ev[1:]):
        end = a["stroke_t"] + a["hold_s"]
        if b["prep_t"] - end < CHAIN:
            hold = max(0.25 if a["held"] else 0.06, b["prep_t"] - a["stroke_t"])
            if a["held"] and hold < a["hold_s"]:
                a["hold_trimmed"] = True
            a["hold_s"] = round(hold, 3)
            a["retract_s"] = round(max(0.15, b["stroke_t"] - a["stroke_t"] - hold), 3)
            a["chained"] = True
        else:
            a["retract_s"] = round(max(0.2, min(a["retract_s"], b["prep_t"] - end - 0.12)), 3)


def window(e):
    return (e["prep_t"], e["stroke_t"] + e["hold_s"] + min(e["retract_s"], 0.2))


def add_beats(ev, pros, sheet, spans, rng) -> list:
    inten = {ln["id"]: ln.get("intensity", 0.7) for ln in sheet["lines"]}
    cands = []
    for w in pros["words"]:
        if bare(w["w"]) in STOP or w["stress"] < BEAT_MIN_STRESS:
            continue
        for n in w["nuclei"]:  # secondary stresses: every strong nucleus, not just the word's main one
            if n["t"] == w["peak_t"] or n["prom"] > 0.0:
                cands.append((w, n["t"]))
    out = list(ev)
    for _ in range(4):
        out.sort(key=lambda e: e["stroke_t"])
        wins = [window(e) for e in out]
        added = False
        for w, tpk in sorted(cands, key=lambda c: -c[0]["stress"]):
            sp = span_of(tpk, spans)
            if not sp:
                continue
            prev_end = max([b for a, b in wins if b <= tpk] + [sp[0] - 0.3])
            next_start = min([a for a, b in wins if a >= tpk] + [sp[1] + 0.3])
            if any(a - 0.1 <= tpk <= b + 0.1 for a, b in wins):
                continue
            if next_start - prev_end < STILL_MAX or tpk - prev_end < 0.5 or next_start - tpk < 0.35:
                continue
            # the type: not the same as either neighbour's
            prev = max((e for e in out if e["stroke_t"] < tpk), key=lambda e: e["stroke_t"], default=None)
            nxt = min((e for e in out if e["stroke_t"] > tpk), key=lambda e: e["stroke_t"], default=None)
            avoid = {e["detail"] for e in (prev, nxt) if e}
            opts = [k for k in ADD_TYPES if k[1] not in avoid]
            kind, detail = rng.choice(opts or list(ADD_TYPES))
            g = {"amp": (0.25 + 0.15 * w["stress"]) * (0.85 + 0.3 * inten.get(w["line"], 0.7)), "held": False}
            x = timed(g, {**w, "peak_t": tpk}, rng, spans)
            x["prep_t"] = round(max(x["prep_t"], prev_end + 0.05), 3)
            out.append({"line": w["line"], "word_i": w["gi"], "word": w["w"], "src": "prosody", "add": True,
                        "type": kind, "detail": detail, "hand": "r", "size": "small", "held": False, **x})
            wins.append(window(out[-1]))
            added = True
        if not added:
            break
    out.sort(key=lambda e: e["stroke_t"])
    return out


def stats(ev, spans) -> dict:
    talk = sum(b - a for a, b in spans)
    rep = [(a["line"], a["word"], b["word"], a["detail"]) for a, b in zip(ev, ev[1:])
           if a["detail"] == b["detail"] and a["detail"] != "count"]
    still, at = 0.0, None
    for a, b in zip(ev, ev[1:]):
        g = b["prep_t"] - window(a)[1]
        if any(x <= window(a)[1] and b["prep_t"] <= y for x, y in spans) and g > still:
            still, at = g, (a["line"], a["word"], b["word"])
    leads = [e["lead_s"] for e in ev]
    return {"gestures": len(ev), "sheet": sum(e["src"] == "sheet" for e in ev),
            "added_beats": sum(e["src"] == "prosody" for e in ev), "speaking_s": round(talk, 2),
            "onsets_per_s": round(len(ev) / talk, 3), "lead_s_range": [min(leads), max(leads)],
            "same_type_twice": rep, "longest_still_while_speaking_s": round(still, 2), "at": at,
            "held": sum(e["held"] for e in ev), "held_trimmed": [(e["line"], e["word"], e["hold_s"]) for e in ev
                                                                  if e.get("hold_trimmed")],
            "pauses_rest": len(spans) - 1}


if __name__ == "__main__":
    film = sys.argv[1] if len(sys.argv) > 1 else "netflix"
    res = plan(film)
    p = EXPL / "acting" / f"timing_{res['who']}.json"
    p.write_text(json.dumps(res, indent=1))
    for e in res["gestures"]:
        print(f'{e["line"]} {e["src"]:7} {e["type"]:7} {e["detail"]:12} {e["hand"]:4} {e["word"]:16} '
              f'prep {e["prep_t"]:6.2f} apex {e["stroke_t"]:6.2f} (f{e["apex_f"]:4}, peak {e["peak_t"]:6.2f}, '
              f'lead {e["lead_s"]:.3f}) hold {e["hold_s"]:.2f} ret {e["retract_s"]:.2f} amp {e["amp"]:.2f} '
              f'en {e["energy"]:.2f}')
    print(json.dumps(res["stats"]))
